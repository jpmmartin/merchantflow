-- Creates the merchant ledger: ledger_accounts, journal_entries, and
-- journal_lines. They belong to the ledger module, and other modules post
-- only through its posting service, inside their own transaction.
--
-- The ledger is double-entry and append-only. A journal entry and its lines
-- are inserted in one transaction; a deferred constraint trigger checks at
-- commit that the entry has exactly the lines it declares (at least two) and
-- that its debits equal its credits in every currency. Entries, lines, and
-- accounts are never updated or deleted: a correction is a new entry.
-- Balances are computed from the lines and never stored. Timestamps have no
-- database default: the application supplies them from its injected clock.
-- Identifiers are UUIDs generated by the application.

CREATE TABLE ledger_accounts (
  id uuid NOT NULL,
  merchant_id uuid NOT NULL,
  -- The code of the account in the chart of accounts, such as 1100.
  code varchar(16) NOT NULL,
  name varchar(100) NOT NULL,
  classification varchar(20) NOT NULL,
  currency char(3) NOT NULL,
  created_at timestamptz NOT NULL,
  CONSTRAINT ledger_accounts_pkey PRIMARY KEY (id),
  CONSTRAINT ledger_accounts_merchant_id_fkey FOREIGN KEY (merchant_id) REFERENCES merchants (id),
  -- One account per merchant, code, and currency; the target of the
  -- ON CONFLICT that creates an account when a posting first needs it.
  CONSTRAINT ledger_accounts_merchant_code_currency_key UNIQUE (merchant_id, code, currency),
  -- Target of the composite foreign key of journal_lines, which also makes a
  -- line's currency the currency of its account.
  CONSTRAINT ledger_accounts_merchant_id_id_currency_key UNIQUE (merchant_id, id, currency),
  CONSTRAINT ledger_accounts_code_check CHECK (code ~ '^[0-9]{4}$'),
  CONSTRAINT ledger_accounts_name_check CHECK (btrim(name) <> ''),
  -- The values mirror LEDGER_ACCOUNT_CLASSIFICATIONS in packages/domain.
  CONSTRAINT ledger_accounts_classification_check CHECK (
    classification IN ('ASSET', 'LIABILITY', 'REVENUE', 'EXPENSE')
  ),
  -- Only the format, as payment_intents.currency: the supported currencies are
  -- those of the domain's exponent table.
  CONSTRAINT ledger_accounts_currency_check CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE TABLE journal_entries (
  id uuid NOT NULL,
  merchant_id uuid NOT NULL,
  -- The business event the entry records: its type and the identifier of its
  -- source. PAYMENT_SALE is the captured sale of one successful payment
  -- attempt, whose ID is the source ID.
  source_type varchar(40) NOT NULL,
  source_id uuid NOT NULL,
  -- The payment intent the entry belongs to, for tracing a payment.
  payment_intent_id uuid,
  description varchar(255) NOT NULL,
  -- How many lines the entry has; the deferred check compares it with the
  -- lines that exist at commit, so no line can be added to a posted entry.
  line_count smallint NOT NULL,
  posted_at timestamptz NOT NULL,
  CONSTRAINT journal_entries_pkey PRIMARY KEY (id),
  CONSTRAINT journal_entries_merchant_id_fkey FOREIGN KEY (merchant_id) REFERENCES merchants (id),
  -- Target of the composite foreign key of journal_lines.
  CONSTRAINT journal_entries_merchant_id_id_key UNIQUE (merchant_id, id),
  -- A source is posted at most once, whatever the merchant.
  CONSTRAINT journal_entries_source_key UNIQUE (source_type, source_id),
  -- The intent of an entry always belongs to its merchant.
  CONSTRAINT journal_entries_payment_intent_fkey FOREIGN KEY (merchant_id, payment_intent_id)
    REFERENCES payment_intents (merchant_id, id),
  CONSTRAINT journal_entries_source_type_check CHECK (source_type IN ('PAYMENT_SALE')),
  CONSTRAINT journal_entries_payment_source_check CHECK (
    source_type <> 'PAYMENT_SALE' OR payment_intent_id IS NOT NULL
  ),
  CONSTRAINT journal_entries_description_check CHECK (btrim(description) <> ''),
  CONSTRAINT journal_entries_line_count_check CHECK (line_count >= 2)
);

CREATE TABLE journal_lines (
  id uuid NOT NULL,
  merchant_id uuid NOT NULL,
  journal_entry_id uuid NOT NULL,
  -- Position of the line in its entry, from 1.
  line_number smallint NOT NULL,
  ledger_account_id uuid NOT NULL,
  side varchar(6) NOT NULL,
  amount_minor bigint NOT NULL,
  currency char(3) NOT NULL,
  CONSTRAINT journal_lines_pkey PRIMARY KEY (id),
  CONSTRAINT journal_lines_entry_line_number_key UNIQUE (journal_entry_id, line_number),
  -- The entry and the account of a line always belong to its merchant, and
  -- the line has the currency of its account.
  CONSTRAINT journal_lines_journal_entry_fkey FOREIGN KEY (merchant_id, journal_entry_id)
    REFERENCES journal_entries (merchant_id, id),
  CONSTRAINT journal_lines_ledger_account_fkey FOREIGN KEY (merchant_id, ledger_account_id, currency)
    REFERENCES ledger_accounts (merchant_id, id, currency),
  CONSTRAINT journal_lines_line_number_check CHECK (line_number >= 1),
  CONSTRAINT journal_lines_side_check CHECK (side IN ('DEBIT', 'CREDIT')),
  CONSTRAINT journal_lines_amount_minor_check CHECK (amount_minor > 0)
);

-- The accounts of a merchant, by code and currency, come from the unique
-- constraint. The entries of a merchant, newest first, and those of one
-- payment intent.
CREATE INDEX journal_entries_merchant_id_posted_at_id_idx
  ON journal_entries (merchant_id, posted_at, id);
CREATE INDEX journal_entries_merchant_id_payment_intent_id_idx
  ON journal_entries (merchant_id, payment_intent_id, posted_at, id)
  WHERE payment_intent_id IS NOT NULL;
-- The lines of an account, for its balance.
CREATE INDEX journal_lines_merchant_id_ledger_account_id_idx
  ON journal_lines (merchant_id, ledger_account_id);

COMMENT ON TABLE ledger_accounts IS 'Ledger accounts of merchants, one per merchant, code, and currency. Never updated or deleted.';
COMMENT ON TABLE journal_entries IS 'Posted journal entries. Never updated or deleted; a correction is a new entry.';
COMMENT ON TABLE journal_lines IS 'Debit and credit lines of journal entries. Never updated or deleted.';
COMMENT ON COLUMN journal_entries.source_id IS 'Identifier of the business event, such as the successful payment attempt of a PAYMENT_SALE.';
COMMENT ON COLUMN journal_lines.amount_minor IS 'Amount in minor units of the currency, always greater than zero; the side says whether it is a debit or a credit.';

-- Checks one entry against the double-entry invariants: it has exactly the
-- number of lines it declares, and in every currency its debits equal its
-- credits.
CREATE FUNCTION ledger_assert_journal_entry_balanced(entry_id uuid) RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  declared smallint;
  actual bigint;
  unbalanced char(3);
BEGIN
  SELECT line_count INTO declared FROM journal_entries WHERE id = entry_id;
  IF NOT FOUND THEN
    RETURN;
  END IF;
  SELECT count(*) INTO actual FROM journal_lines WHERE journal_entry_id = entry_id;
  IF actual <> declared THEN
    RAISE EXCEPTION 'journal_entries: entry % declares % lines and has %', entry_id, declared, actual
      USING ERRCODE = 'check_violation';
  END IF;
  SELECT currency INTO unbalanced
    FROM journal_lines
    WHERE journal_entry_id = entry_id
    GROUP BY currency
    HAVING sum(CASE WHEN side = 'DEBIT' THEN amount_minor ELSE 0 END)
        <> sum(CASE WHEN side = 'CREDIT' THEN amount_minor ELSE 0 END)
    LIMIT 1;
  IF FOUND THEN
    RAISE EXCEPTION 'journal_entries: entry % does not balance in %', entry_id, unbalanced
      USING ERRCODE = 'check_violation';
  END IF;
END;
$$;

CREATE FUNCTION journal_entries_check_balanced() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  PERFORM ledger_assert_journal_entry_balanced(NEW.id);
  RETURN NULL;
END;
$$;

CREATE FUNCTION journal_lines_check_balanced() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  PERFORM ledger_assert_journal_entry_balanced(NEW.journal_entry_id);
  RETURN NULL;
END;
$$;

-- Deferred to the commit, so an entry and its lines can be inserted one
-- statement at a time; an entry with no lines is caught by the trigger on
-- journal_entries, and a line added to a posted entry by the one on
-- journal_lines.
CREATE CONSTRAINT TRIGGER journal_entries_balanced
AFTER INSERT ON journal_entries
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION journal_entries_check_balanced();

CREATE CONSTRAINT TRIGGER journal_lines_balanced
AFTER INSERT ON journal_lines
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION journal_lines_check_balanced();

-- The ledger is append-only: an update, a delete, or a truncate of an
-- account, an entry, or a line is rejected for every statement.
CREATE FUNCTION ledger_reject_change() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  RAISE EXCEPTION '%: % is not allowed', TG_TABLE_NAME, TG_OP
    USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE TRIGGER ledger_accounts_restrict_change
BEFORE UPDATE OR DELETE OR TRUNCATE ON ledger_accounts
FOR EACH STATEMENT
EXECUTE FUNCTION ledger_reject_change();

CREATE TRIGGER journal_entries_restrict_change
BEFORE UPDATE OR DELETE OR TRUNCATE ON journal_entries
FOR EACH STATEMENT
EXECUTE FUNCTION ledger_reject_change();

CREATE TRIGGER journal_lines_restrict_change
BEFORE UPDATE OR DELETE OR TRUNCATE ON journal_lines
FOR EACH STATEMENT
EXECUTE FUNCTION ledger_reject_change();
