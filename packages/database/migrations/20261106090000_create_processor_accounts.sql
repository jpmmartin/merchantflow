-- Creates the processor_accounts table: the provider accounts (for now, Stripe
-- test accounts) a merchant connects to collect payments.
--
-- The secret key is stored only encrypted with AES-256-GCM under a master key
-- that never reaches the database: the ciphertext, its 12-byte IV, its 16-byte
-- authentication tag, and the version of the master key. The associated data of
-- the encryption names the merchant and the account, so a ciphertext copied to
-- another row fails to decrypt. The publishable key is not secret and is stored
-- in plain text. Timestamps have no database default: the application supplies
-- them from its injected clock. Identifiers are UUIDs generated by the
-- application.

CREATE TABLE processor_accounts (
  id uuid NOT NULL,
  merchant_id uuid NOT NULL,
  provider varchar(32) NOT NULL,
  display_name varchar(100) NOT NULL,
  provider_account_id varchar(255) NOT NULL,
  publishable_key varchar(255) NOT NULL,
  secret_key_ciphertext bytea NOT NULL,
  secret_key_iv bytea NOT NULL,
  secret_key_auth_tag bytea NOT NULL,
  secret_key_version smallint NOT NULL,
  secret_key_hint varchar(4) NOT NULL,
  enabled boolean NOT NULL,
  is_default boolean NOT NULL,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT processor_accounts_pkey PRIMARY KEY (id),
  CONSTRAINT processor_accounts_merchant_id_fkey FOREIGN KEY (merchant_id) REFERENCES merchants (id),
  -- Target of the composite foreign keys of later tables, such as payment
  -- attempts, so a row of one merchant can never reference another merchant's
  -- account.
  CONSTRAINT processor_accounts_merchant_id_id_key UNIQUE (merchant_id, id),
  -- Checked by format only: which providers exist is decided by the adapters
  -- the application registers, so a new provider needs no migration.
  CONSTRAINT processor_accounts_provider_check CHECK (provider ~ '^[a-z][a-z0-9_]{1,31}$'),
  CONSTRAINT processor_accounts_display_name_check CHECK (display_name ~ '\S'),
  CONSTRAINT processor_accounts_provider_account_id_check CHECK (provider_account_id ~ '^\S+$'),
  CONSTRAINT processor_accounts_publishable_key_check CHECK (publishable_key ~ '^\S+$'),
  CONSTRAINT processor_accounts_secret_key_ciphertext_check CHECK (octet_length(secret_key_ciphertext) > 0),
  CONSTRAINT processor_accounts_secret_key_iv_check CHECK (octet_length(secret_key_iv) = 12),
  CONSTRAINT processor_accounts_secret_key_auth_tag_check CHECK (octet_length(secret_key_auth_tag) = 16),
  CONSTRAINT processor_accounts_secret_key_version_check CHECK (secret_key_version >= 1),
  CONSTRAINT processor_accounts_secret_key_hint_check CHECK (char_length(secret_key_hint) = 4),
  -- A disabled account cannot be the one payments use.
  CONSTRAINT processor_accounts_default_enabled_check CHECK (enabled OR NOT is_default),
  CONSTRAINT processor_accounts_updated_at_check CHECK (updated_at >= created_at)
);

-- At most one default account per merchant.
CREATE UNIQUE INDEX processor_accounts_one_default_per_merchant_idx
  ON processor_accounts (merchant_id)
  WHERE is_default;

-- A provider account is connected at most once per merchant while enabled; a
-- disabled connection does not block connecting it again.
CREATE UNIQUE INDEX processor_accounts_enabled_provider_account_idx
  ON processor_accounts (merchant_id, provider, provider_account_id)
  WHERE enabled;

-- The list of a merchant's accounts filters by merchant_id and orders by
-- (created_at, id).
CREATE INDEX processor_accounts_merchant_id_created_at_id_idx
  ON processor_accounts (merchant_id, created_at, id);

COMMENT ON TABLE processor_accounts IS 'Provider accounts a merchant connects. The secret key is stored only encrypted; the master key is never stored in the database.';
COMMENT ON COLUMN processor_accounts.provider IS 'Provider code of the adapter, for example stripe.';
COMMENT ON COLUMN processor_accounts.provider_account_id IS 'Identifier of the account at the provider, for example a Stripe acct_ ID. Display data, not a secret.';
COMMENT ON COLUMN processor_accounts.publishable_key IS 'Publishable key used by the browser card form. Not a secret.';
COMMENT ON COLUMN processor_accounts.secret_key_ciphertext IS 'AES-256-GCM ciphertext of the secret key. Never the secret key itself.';
COMMENT ON COLUMN processor_accounts.secret_key_version IS 'Version of the master key that encrypted the secret key.';
COMMENT ON COLUMN processor_accounts.secret_key_hint IS 'Last four characters of the secret key, shown to identify it.';
COMMENT ON COLUMN processor_accounts.is_default IS 'The account payments use. At most one per merchant, and only an enabled one.';

-- The owner, the provider identity, and the creation time of an account never
-- change: the encryption's associated data names the merchant and the account,
-- and a later payment attempt must keep referring to the same provider account.
CREATE FUNCTION processor_accounts_reject_identity_update() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF (NEW.id, NEW.merchant_id, NEW.provider, NEW.provider_account_id, NEW.created_at)
     IS DISTINCT FROM
     (OLD.id, OLD.merchant_id, OLD.provider, OLD.provider_account_id, OLD.created_at) THEN
    RAISE EXCEPTION 'processor_accounts: id, merchant_id, provider, provider_account_id, and created_at cannot be changed'
      USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER processor_accounts_restrict_update
BEFORE UPDATE ON processor_accounts
FOR EACH ROW
EXECUTE FUNCTION processor_accounts_reject_identity_update();
