import {
  Body,
  Controller,
  Get,
  Header,
  HttpCode,
  Param,
  Post,
} from '@nestjs/common';
import {
  ApiBearerAuth,
  ApiOperation,
  ApiResponse,
  ApiTags,
} from '@nestjs/swagger';
import { CurrentPrincipal } from '../../auth/api/current-principal.decorator.js';
import { Roles } from '../../auth/api/route-access.js';
import type { Principal } from '../../auth/application/principal.js';
import { ApiErrorResponses } from '../../errors/api/api-error-responses.decorator.js';
import { CorrelationId } from '../../logging/correlation-id.decorator.js';
import { CreateMerchantUserService } from '../application/create-merchant-user.service.js';
import { DisableMerchantUserService } from '../application/disable-merchant-user.service.js';
import { ListMerchantUsersService } from '../application/list-merchant-users.service.js';
import {
  INSUFFICIENT_ROLE_DOC,
  NOT_FOUND_DOC,
  UNAUTHENTICATED_DOC,
  VALIDATION_FAILED_DOC,
} from './merchant-error-docs.js';
import { toApiException } from './merchant-failures.js';
import {
  toCreatedMerchantUserResponse,
  toMerchantUserListResponse,
  toMerchantUserResponse,
} from './merchant.presenter.js';
import {
  createdMerchantUserResponseSchema,
  createMerchantUserSchema,
  merchantIdParamSchema,
  merchantUserListResponseSchema,
  merchantUserResponseSchema,
  userIdParamSchema,
  type CreatedMerchantUserResponse,
  type CreateMerchantUserBody,
  type MerchantUserListResponse,
  type MerchantUserResponse,
} from './merchant.schemas.js';

/** See `ANY_ROLE` in the merchants controller: the use case answers 404 first. */
const ANY_ROLE = [
  'PLATFORM_ADMIN',
  'MERCHANT_ADMIN',
  'MERCHANT_READ_ONLY',
] as const;

@ApiTags('Merchant users')
@ApiBearerAuth('bearer')
@Controller('merchants/:id/users')
export class MerchantUsersController {
  constructor(
    private readonly createUser: CreateMerchantUserService,
    private readonly listUsers: ListMerchantUsersService,
    private readonly disableUser: DisableMerchantUserService,
  ) {}

  @Post()
  @Roles(ANY_ROLE)
  @Header('Cache-Control', 'no-store')
  @ApiOperation({
    summary: 'Create a user of a merchant',
    description:
      'Roles: PLATFORM_ADMIN for any merchant; MERCHANT_ADMIN for its own. The user gets the role MERCHANT_ADMIN and a password generated by the server, which the response holds once; it is stored only as a hash and cannot be retrieved again. The response is not cacheable (Cache-Control: no-store). The email is unique across the platform, so a taken email gets 409 USER_EMAIL_TAKEN, which reveals that the address is registered. A merchant role gets 404 for another merchant, and MERCHANT_READ_ONLY gets 403 for its own.',
  })
  @ApiResponse({
    status: 201,
    description:
      'The user was created. This is the only time its password is shown.',
    standardSchema: createdMerchantUserResponseSchema,
  })
  @ApiErrorResponses(
    VALIDATION_FAILED_DOC,
    UNAUTHENTICATED_DOC,
    INSUFFICIENT_ROLE_DOC,
    NOT_FOUND_DOC,
    {
      status: 409,
      description:
        'USER_EMAIL_TAKEN: a user of any merchant or of the platform already has this email. Nothing was created.',
    },
  )
  async create(
    @CurrentPrincipal() principal: Principal,
    @CorrelationId() correlationId: string,
    @Param('id', { schema: merchantIdParamSchema }) merchantId: string,
    @Body({ schema: createMerchantUserSchema }) body: CreateMerchantUserBody,
  ): Promise<CreatedMerchantUserResponse> {
    const result = await this.createUser.execute({
      principal,
      correlationId,
      merchantId,
      email: body.email,
      displayName: body.display_name,
    });
    if (!result.ok) throw toApiException(result.code);
    return toCreatedMerchantUserResponse(result.user, result.initialPassword);
  }

  @Get()
  @Roles(ANY_ROLE)
  @ApiOperation({
    summary: 'List the users of a merchant',
    description:
      'Roles: PLATFORM_ADMIN for any merchant; MERCHANT_ADMIN and MERCHANT_READ_ONLY for their own. Lists every user, disabled ones included, oldest first. Never returns a password or its hash. Another merchant is 404.',
  })
  @ApiResponse({
    status: 200,
    description: 'The users of the merchant.',
    standardSchema: merchantUserListResponseSchema,
  })
  @ApiErrorResponses(VALIDATION_FAILED_DOC, UNAUTHENTICATED_DOC, NOT_FOUND_DOC)
  async list(
    @CurrentPrincipal() principal: Principal,
    @Param('id', { schema: merchantIdParamSchema }) merchantId: string,
  ): Promise<MerchantUserListResponse> {
    const result = await this.listUsers.execute({ principal, merchantId });
    if (!result.ok) throw toApiException(result.code);
    return toMerchantUserListResponse(result.users);
  }

  @Post(':userId/disable')
  @HttpCode(200)
  @Roles(ANY_ROLE)
  @ApiOperation({
    summary: 'Disable a user of a merchant',
    description:
      'Roles: PLATFORM_ADMIN for any merchant; MERCHANT_ADMIN for its own. The user can no longer sign in, and every session it has is revoked in the same transaction, so its tokens get 401 at their next request. A signed-in user cannot disable itself (409 USER_SELF_DISABLE_NOT_ALLOWED). Disabling a disabled user succeeds and changes nothing. A user of another merchant, a platform user, and an unknown id are 404. A merchant role gets 404 for another merchant, and MERCHANT_READ_ONLY gets 403 for its own.',
  })
  @ApiResponse({
    status: 200,
    description: 'The user is disabled.',
    standardSchema: merchantUserResponseSchema,
  })
  @ApiErrorResponses(
    VALIDATION_FAILED_DOC,
    UNAUTHENTICATED_DOC,
    INSUFFICIENT_ROLE_DOC,
    NOT_FOUND_DOC,
    {
      status: 409,
      description:
        'USER_SELF_DISABLE_NOT_ALLOWED: the signed-in user named itself. Nothing was changed.',
    },
  )
  async disable(
    @CurrentPrincipal() principal: Principal,
    @CorrelationId() correlationId: string,
    @Param('id', { schema: merchantIdParamSchema }) merchantId: string,
    @Param('userId', { schema: userIdParamSchema }) userId: string,
  ): Promise<MerchantUserResponse> {
    const result = await this.disableUser.execute({
      principal,
      correlationId,
      merchantId,
      userId,
    });
    if (!result.ok) throw toApiException(result.code);
    return toMerchantUserResponse(result.user);
  }
}
